        /* =====================================================
           MODAL IMAGE SLIDER
        ===================================================== */

        function changeModalImage(
            direction
        ) {

            if (!selectedCommercial) {

                return;
            }


            modalImageIndex +=
                direction;


            if (
                modalImageIndex
                >= selectedCommercial.images.length
            ) {

                modalImageIndex = 0;
            }


            if (
                modalImageIndex < 0
            ) {

                modalImageIndex =
                    selectedCommercial.images.length - 1;
            }


            document.getElementById(
                "modalPropertyImage"
            ).src =
                selectedCommercial.images[
                    modalImageIndex
                ];

        }


        /* =====================================================
           CLOSE MODAL
        ===================================================== */

        function closeProperty() {

            document.getElementById(
                "propertyModal"
            ).style.display =
                "none";


            document.body.style.overflow =
                "auto";

        }


        /* =====================================================
           SEARCH
        ===================================================== */

        function searchCommercial() {

            const searchText =
                document.getElementById(
                    "searchInput"
                ).value
                .trim()
                .toLowerCase();


            const filteredCommercials =
                commercials.filter(
                    (property) => {

                        return (

                            property.title
                                .toLowerCase()
                                .includes(
                                    searchText
                                )

                            ||

                            property.brand
                                .toLowerCase()
                                .includes(
                                    searchText
                                )

                            ||

                            property.location
                                .toLowerCase()
                                .includes(
                                    searchText
                                )

                            ||

                            property.type
                                .toLowerCase()
                                .includes(
                                    searchText
                                )

                        );

                    }
                );


            renderCommercials(
                filteredCommercials
            );

        }


        /* =====================================================
           ENTER KEY SEARCH
        ===================================================== */

        document
            .getElementById("searchInput")
            .addEventListener(
                "keydown",
                function(event) {

                    if (
                        event.key === "Enter"
                    ) {

                        searchCommercial();

                    }

                }
            );


        /* =====================================================
           BOOK PROPERTY
        ===================================================== */

        function bookProperty() {

            const date =
                document.getElementById(
                    "bookingDate"
                ).value;


            const payment =
                document.getElementById(
                    "paymentOption"
                ).value;


            if (date === "") {

                alert(
                    "Please select a booking date."
                );

                return;
            }


            if (payment === "") {

                alert(
                    "Please select a booking option."
                );

                return;
            }


            alert(
                "Booking request submitted successfully!"
            );

        }


