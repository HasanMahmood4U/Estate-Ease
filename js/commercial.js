        /* =====================================================
           URL SEARCH
        ===================================================== */

        function loadURLSearch() {

            const params =
                new URLSearchParams(
                    window.location.search
                );


            const search =
                params.get("search");


            if (search) {

                document.getElementById(
                    "searchInput"
                ).value =
                    search;


                searchCommercial();

            } else {

                renderCommercials();

            }

        }


